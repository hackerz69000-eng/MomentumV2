-- Records finalized assessment questions to prevent cross-tab/device reuse.
-- Additive only: existing study data and attempts are retained.
CREATE TABLE IF NOT EXISTS public.generated_assessment_questions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  set_id uuid NOT NULL REFERENCES public.study_sets(id) ON DELETE CASCADE,
  generation_id uuid NOT NULL,
  question_text text NOT NULL CHECK (length(btrim(question_text)) > 0),
  normalized_question text NOT NULL CHECK (length(btrim(normalized_question)) > 0),
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (user_id, set_id, normalized_question)
);

CREATE INDEX IF NOT EXISTS generated_assessment_questions_recent_idx
  ON public.generated_assessment_questions (user_id, set_id, created_at DESC);

ALTER TABLE public.generated_assessment_questions ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Users read their generated assessment questions" ON public.generated_assessment_questions;
CREATE POLICY "Users read their generated assessment questions"
  ON public.generated_assessment_questions FOR SELECT TO authenticated
  USING (auth.uid() = user_id);
REVOKE INSERT, UPDATE, DELETE, TRUNCATE, REFERENCES, TRIGGER
  ON public.generated_assessment_questions FROM anon, authenticated;
GRANT SELECT ON public.generated_assessment_questions TO authenticated;

-- Backfill questions from completed attempts so the new guard recognizes old material.
INSERT INTO public.generated_assessment_questions
  (user_id, set_id, generation_id, question_text, normalized_question)
SELECT a.user_id, a.set_id, gen_random_uuid(), btrim(r.value->>'q'),
  btrim(regexp_replace(lower(regexp_replace(btrim(r.value->>'q'), '[^[:alnum:]]+', ' ', 'g')), '\s+', ' ', 'g'))
FROM public.quiz_attempts a
CROSS JOIN LATERAL jsonb_array_elements(CASE WHEN jsonb_typeof(a.results) = 'array' THEN a.results ELSE '[]'::jsonb END) r(value)
WHERE coalesce(r.value->>'q', '') <> ''
ON CONFLICT (user_id, set_id, normalized_question) DO NOTHING;

CREATE OR REPLACE FUNCTION public.reserve_assessment_questions(p_generation_id uuid, p_source_revisions jsonb, p_questions jsonb)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_user_id uuid := auth.uid();
  v_item record;
  v_text text;
  v_normalized text;
  v_existing_generation uuid;
  v_current_revision uuid;
BEGIN
  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'Sign in before saving generated questions.' USING ERRCODE = '28000';
  END IF;
  IF p_generation_id IS NULL OR jsonb_typeof(p_source_revisions) <> 'object' OR jsonb_typeof(p_questions) <> 'array' OR jsonb_array_length(p_questions) = 0 THEN
    RAISE EXCEPTION 'A generation ID and at least one question are required.' USING ERRCODE = '22023';
  END IF;
  IF EXISTS (
    SELECT 1 FROM (
      SELECT (value->>'set_id')::uuid AS set_id, btrim(regexp_replace(lower(value->>'question_key'), '\s+', ' ', 'g')) AS question_key, count(*) AS n
      FROM jsonb_array_elements(p_questions) GROUP BY 1, 2 HAVING count(*) > 1
    ) duplicate_rows
  ) THEN RETURN false; END IF;

  -- Serialize finalization per user and study set; sorted IDs avoid lock-order deadlocks.
  FOR v_item IN SELECT DISTINCT (value->>'set_id')::uuid AS set_id
    FROM jsonb_array_elements(p_questions) ORDER BY set_id
  LOOP
    SELECT s.generation_source_revision INTO v_current_revision FROM public.study_sets s
      WHERE s.id = v_item.set_id AND s.user_id = v_user_id FOR UPDATE;
    IF NOT FOUND THEN
      RAISE EXCEPTION 'Study set not found.' USING ERRCODE = 'P0002';
    END IF;
    IF v_current_revision::text IS DISTINCT FROM (p_source_revisions ->> (v_item.set_id::text)) THEN
      RAISE EXCEPTION 'Study material changed while Momentum was generating. The outdated assessment was not saved. Retry with current material.' USING ERRCODE = '40001';
    END IF;
    PERFORM pg_advisory_xact_lock(hashtextextended(v_user_id::text || ':' || v_item.set_id::text, 0));
  END LOOP;

  -- A nested block ensures a collision rolls back every insert in this request.
  BEGIN
    FOR v_item IN SELECT value FROM jsonb_array_elements(p_questions)
    LOOP
      v_text := btrim(v_item.value->>'question');
      IF v_text IS NULL OR v_text = '' OR (v_item.value->>'set_id') IS NULL THEN
        RAISE EXCEPTION 'Invalid question reservation.' USING ERRCODE = '22023';
      END IF;
      v_normalized := btrim(regexp_replace(lower(v_item.value->>'question_key'), '\s+', ' ', 'g'));
      IF v_normalized = '' THEN RAISE EXCEPTION 'Invalid question reservation.' USING ERRCODE = '22023'; END IF;
      SELECT generation_id INTO v_existing_generation
        FROM public.generated_assessment_questions
        WHERE user_id = v_user_id AND set_id = (v_item.value->>'set_id')::uuid
          AND normalized_question = v_normalized;
      IF FOUND THEN
        IF v_existing_generation = p_generation_id THEN CONTINUE; END IF;
        RAISE EXCEPTION 'A question was already used for this study material.' USING ERRCODE = '23505';
      END IF;
      INSERT INTO public.generated_assessment_questions
        (user_id, set_id, generation_id, question_text, normalized_question)
      VALUES (v_user_id, (v_item.value->>'set_id')::uuid, p_generation_id, v_text, v_normalized);
    END LOOP;
  EXCEPTION WHEN unique_violation THEN
    RETURN false;
  END;
  RETURN true;
EXCEPTION WHEN unique_violation THEN
  RETURN false;
END;
$$;

REVOKE ALL ON FUNCTION public.reserve_assessment_questions(uuid, jsonb, jsonb) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.reserve_assessment_questions(uuid, jsonb, jsonb) TO authenticated;
